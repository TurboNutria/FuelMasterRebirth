import Foundation

/// Response of every `EstacionesTerrestres…` endpoint.
struct StationListDTO: Decodable, Sendable {
    let date: String
    let stations: [StationDTO]
    let result: String

    enum CodingKeys: String, CodingKey {
        case date = "Fecha"
        case stations = "ListaEESSPrecio"
        case result = "ResultadoConsulta"
    }
}

/// One station. Every value arrives as text, and the set of keys depends on the endpoint
/// (`PrecioProducto` for single-product calls, one `Precio …` key per product otherwise),
/// so the raw dictionary is kept and read through named accessors.
struct StationDTO: Decodable, Sendable {
    let fields: [String: String]

    init(from decoder: any Decoder) throws {
        fields = try decoder.singleValueContainer().decode([String: String].self)
    }

    init(fields: [String: String]) {
        self.fields = fields
    }

    subscript(_ key: String) -> String { fields[key]?.trimmingCharacters(in: .whitespaces) ?? "" }

    var id: String { self["IDEESS"] }
    var sign: String { self["Rótulo"] }
    var street: String { self["Dirección"] }
    var postcode: String { self["C.P."] }
    var locality: String { self["Localidad"] }
    var municipality: String { self["Municipio"] }
    var municipalityID: String { self["IDMunicipio"] }
    var province: String { self["Provincia"] }
    var provinceID: String { self["IDProvincia"] }
    var latitude: String { self["Latitud"] }
    var longitude: String { self["Longitud (WGS84)"] }
    var hours: String { self["Horario"] }
    var roadSide: String { self["Margen"] }
    /// "P" public, "R" restricted (members or fleets only).
    var saleType: String { self["Tipo Venta"] }
    /// Single-product endpoints only.
    var productPrice: String { self["PrecioProducto"] }
}

/// `Listados/Provincias/` (note the ministry's `IDPovincia` typo).
struct ProvinceDTO: Decodable, Sendable {
    let id: String
    let name: String
    let regionID: String
    let regionName: String

    enum CodingKeys: String, CodingKey {
        case id = "IDPovincia"
        case name = "Provincia"
        case regionID = "IDCCAA"
        case regionName = "CCAA"
    }
}

/// Bundled `provinces.json`, generated by `Tools/generate_geography.py`.
struct BundledProvinceDTO: Decodable, Sendable {
    let id: String
    let name: String
    let regionID: String
    let regionName: String
    /// [minLat, minLon, maxLat, maxLon]
    let bounds: [Double]
    let hull: [[Double]]
    let samples: [[Double]]
}

/// Bundled `municipalities.json`.
struct BundledMunicipalityDTO: Decodable, Sendable {
    let id: String
    let name: String
    let provinceID: String
}
